export const navigationSections = ["Overview", "Projects", "Build", "Train", "Use", "System"] as const;

export function getNavigationItem(pathname: string) {
  if (pathname.startsWith("/projects/") && pathname.endsWith("/data")) {
    return navigationItems.find((item) => item.title === "Data") ?? navigationItems[0];
  }
  if (pathname.startsWith("/projects/") && pathname.endsWith("/tokenizer")) {
    return navigationItems.find((item) => item.title === "Tokenizer") ?? navigationItems[0];
  }
  if (pathname.startsWith("/projects/")) {
    return navigationItems.find((item) => item.href === "/projects") ?? navigationItems[0];
  }
  return navigationItems.find((item) => item.href === pathname) ?? navigationItems[0];
}

export function getBreadcrumbs(pathname: string) {
  const current = getNavigationItem(pathname);
  if (current.href === "/") {
    return [current];
  }
  return [navigationItems[0], current];
}
